AUDIT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'orig', 'audit_v23')


def derive_audit(report):
    """Run the bitcode-free audit scripts into $FPEA_OUTDIR and compare with data/results:
    boot2.py (negative pool -> ratio/expansion estimators, unit bootstrap; reads recon_pool2.json),
    wl_ext.py (whitelist-only decomposition from wl_only.json + defmap + link layer),
    typed_cmp_unit.py (fpea14 vs fpea16 unit outputs, needs data/fpea_out/rf14_5.17.11)."""
    env = dict(os.environ, FPEA_AUDIT_OUT=O, FPEA_RESULTS=RES)
    for script, out in (('boot2.py', 'boot2_results.json'), ('wl_ext.py', 'wl_ext.json'),
                        ('typed_cmp_unit.py', 'typed_mode_cmp.json')):
        r = subprocess.run([sys.executable, f'{AUDIT}/{script}'], env=env, capture_output=True,
                           text=True)
        if r.returncode != 0:
            report.append((f'{out} (audit_v23/{script})', 'FAILED: ' + r.stderr.strip()[-200:]))
            continue
        compare(report, f'{out} (audit_v23/{script})', load_json(f'{O}/{out}'), f'{RES}/{out}')


